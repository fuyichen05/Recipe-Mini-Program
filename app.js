// app.js
// ============================================================
// 家庭菜谱记录 · 云开发环境配置
// ------------------------------------------------------------
// 1. 在微信开发者工具顶部点击「云开发」按钮开通云开发（选择免费的基础套餐即可），
//    开通后在云开发控制台左上角可以看到「环境 ID」（形如 cloud1-3g1axxxxxxxx）。
// 2. 把环境 ID 填到下面 CLOUD_ENV_ID 的引号里。
//    如果你的账号只创建过一个环境，留空也可以（会自动使用默认环境）。
//
// 3. ⚠️ 数据库权限（非常重要，不配置家人之间无法互相编辑）：
//    云开发控制台 → 数据库 → 集合 recipes → 权限设置 → 「自定义安全规则」，
//    填入以下 JSON：
//    {
//      "read": true,
//      "write": true
//    }
//    注意：不要使用「基础权限」的四个选项，基础权限无法实现"所有人可读可写"，
//    也就无法实现家人互相编辑/删除对方添加的菜品。
// ============================================================
const CLOUD_ENV_ID = '' // TODO: 填入你的云开发环境 ID（见 README）

App({
  onLaunch() {
    if (!wx.cloud) {
      console.error('当前基础库版本过低（云开发需要 2.2.3+），请升级基础库版本')
      return
    }
    wx.cloud.init(
      CLOUD_ENV_ID
        ? { env: CLOUD_ENV_ID, traceUser: true }
        : { traceUser: true }
    )
  },

  globalData: {
    // 详情页点「编辑」时，通过它把待编辑数据带给添加页
    // （添加页是 tabBar 页面，无法通过 URL 参数传递编辑目标）
    editingRecipe: null
  }
})
